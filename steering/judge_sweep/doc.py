          "A, C and D exactly once, and the combinations rotate across batches.",
          "- Changes: A = 3 rephrasings of the main sentences; B = no \"other is the last resort\" (other / none is "
          "a normal answer); C = 3 seeded orders of the categories; D = 3 example sets; E = evidence, then analysis, "
          "then the label, then the intensity; F = a collapsed option.",
          "- Worked examples (D): personas drawn at random from the options the judge sees. The answer is a real "
