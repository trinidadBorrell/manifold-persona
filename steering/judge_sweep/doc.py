def variants(J):
    """The rephrased sentences (A) and the example personas per set (D) of a judge."""
    A = {"J2": [P.J2_INTRO, P.J2_RULE, P.J2_OTHER, P.J2_COLLAPSED, P.J2_ORDER], "J8": [P.J2_INTRO, P.J2_RULE],
         "J9": [P.J2_INTRO, P.J2_RULE], "J4": [P.AA_INTRO, P.AA_ORDER], "J5": [P.J5_INTRO, P.J5_WHAT, P.J5_IGNORE],
         "J6": [P.J6_INTRO, P.J6_WHAT, P.J6_NAMING], "J7": [P.J7_ASK]}.get(J)
    if not A:
        return "Single draw, no variants (verbatim prompt; the [role] line is the target and its definition)."
    out = ["**What the 3 rephrasings (A) change** — each block below exists in 3 versions:", ""]
    for blk in A[:2]:
        for i, t in enumerate(blk):
            out.append("- v%d: %s" % (i, t.replace("\n", " ").replace("{names}", "[names]")[:400]))
        out.append("")
    if J == "J4":
        out.append("**Example sets (D):** set 0 = the 8 original Assistant Axis examples; set 1 = 7 new examples, "
                   "including one acting as a different role (other); set 2 = 5 examples, including a language switch "
                   "(nonsensical). The grid definitions are also rephrased (A).")
    else:
        opts = P.all_roles() if J in ("J6", "J7", "J8", "J9") else None
        if opts is None:
            out.append("**Example sets (D):** drawn per pair from its options; see the instructions files.")
        else:
            salt = {"J6": "J6|all|open", "J7": "J7|all|min"}.get(J, J + "|all")
            for d in range(3):
                ex = P.example_set(d, opts, salt)
                out.append("- set %d: %s" % (d, ", ".join(e["role"] or "collapsed (invented)" for e in ex)))
    return "\n".join(out)


if __name__ == "__main__":
    main()
