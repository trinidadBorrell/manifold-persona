from __future__ import annotations

import json
import re
from pathlib import Path

from steering.judge_sweep import prompts as P
from steering.judge_sweep.build import PM

OUT = P._REPO / "docs" / "judge_prompts_2026-10-14.md"
JS = PM / "JS"


def shorten_roles(text):
    """Long role lists in the doc: keep the first 6 lines and say how many follow."""
    lines, out, run = text.split("\n"), [], 0
    for ln in lines:
        is_role = bool(re.match(r"- [a-z_]+: ", ln)) and not ln.startswith(("- other:", "- collapsed:", "- evidence",
                                                                           "- analysis", "- persona", "- intensity",
                                                                           "- ranking", "- score"))
        run = run + 1 if is_role else 0
        if run <= 6:
            if run == 0 and out and out[-1].startswith("  [... "):
                pass
            out.append(ln)
        elif run == 7:
            out.append("  [... the remaining role lines, same format; full list in the appendix ...]")
    names = re.search(r"one of these personas\? (.+)", text)
    s = "\n".join(out)
    if names and len(names.group(1)) > 300:
        s = s.replace(names.group(1), names.group(1)[:200] + " ... [all 275 role names, shuffled]")
    return s


